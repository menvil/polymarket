/**
 * PM2-конфигурация для Polymarket data-collector.
 *
 * Запуск:
 *   npm run build
 *   pm2 start ecosystem.config.cjs
 *   pm2 logs polymarket-collector
 *   pm2 stop polymarket-collector
 *
 * Почему fork, а не cluster:
 *   Сервис держит глобальное состояние (подписки источников, открытые окна
 *   записи, идущие финализации). Cluster-режим породил бы N копий, которые
 *   подписались бы на одни и те же рынки и писали бы в одни и те же файлы.
 */
/**
 * Сколько супервизор ждёт после SIGTERM, прежде чем прислать SIGKILL (мс).
 *
 * @remarks
 * ЕДИНСТВЕННЫЙ источник этого числа: оно уходит и в `kill_timeout` pm2, и в
 * окружение процесса. Приложение сверяет с ним свой бюджет остановки и
 * отказывается стартовать, если бюджет не меньше — иначе SIGKILL пришёл бы
 * посреди лестницы, молча выключив весь механизм упорядоченной остановки.
 */
const KILL_TIMEOUT_MS = 60000;

module.exports = {
  apps: [
    {
      name: 'polymarket-collector',
      cwd: __dirname,
      script: 'dist/main.js',

      // --max-old-space-size=4096 согласован с npm run start.
      // --expose-gc полезен для ручного global.gc() при отладке утечек.
      node_args: '--max-old-space-size=4096 --expose-gc --env-file=.env',

      exec_mode: 'fork',
      instances: 1,

      // Чуть ниже max-old-space-size (4096 MB) — чтобы pm2 успел перезапустить
      // до того, как V8 упадёт в OOM.
      max_memory_restart: '3500M',

      autorestart: true,
      // Бэкофф между рестартами, чтобы не долбить API при сломанной конфигурации.
      restart_delay: 5000,
      // Если процесс упал >10 раз подряд менее чем за 60s — стопаем (видимо, баг).
      max_restarts: 10,
      min_uptime: '60s',

      // Остановка ограничена САМИМ приложением: COLLECTOR_SHUTDOWN_DEADLINE_MS
      // (дефолт 10 с) — по его истечении лестница бросается и процесс выходит.
      // Поэтому здесь нужен не «сколько может занять штатная остановка», а
      // «через сколько считать процесс зависшим».
      //
      // Прежние 180 с исходили из того, что остановка ЖДЁТ финализаций. Она
      // ждала: замер run-02 — 26 минут, теоретический потолок ~75 (дожитие
      // 15-минутного рынка + enrichmentMaxWaitMs). Ни один таймаут этого не
      // покрывал, а покрывающий сделал бы бесполезным сам механизм убийства:
      // процесс, вышедший за max_memory_restart или зависший, должен
      // перезапускаться немедленно, а не через час.
      //
      // Дренаж из лестницы убран, недоархивированное теряется осознанно и
      // подметается startup cleanup.
      //
      // Значение ОБЯЗАНО быть больше COLLECTOR_SHUTDOWN_DEADLINE_MS (30 с):
      // иначе SIGKILL придёт ровно в тот момент, когда процесс сам решает
      // выходить, и упорядоченность остановки потеряется. Шестьдесят дают
      // тридцать секунд запаса, и SIGKILL снова означает ровно то, что
      // должен: процесс не отвечает.
      kill_timeout: KILL_TIMEOUT_MS,
      wait_ready: false,

      watch: false,

      // Общий лог; stderr и stdout склеены.
      merge_logs: true,
      log_date_format: 'DD-MM HH:mm:ss Z',
      log_type: 'raw',
      out_file: './logs/collector.log',
      error_file: './logs/collector-error.log',

      env: {
        NODE_ENV: 'production',
        // Процесс обязан знать бюджет супервизора, чтобы свериться с ним на
        // старте. Знание это законное: «мой супервизор убьёт меня через N мс»
        // — не деталь pm2, а контракт окружения. Само имя супервизора коду
        // по-прежнему неизвестно.
        COLLECTOR_KILL_TIMEOUT_MS: String(KILL_TIMEOUT_MS),
        // LOG_LEVEL, CEX_CONFIG, прочее — берутся из .env (--env-file).
      },
    },
  ],
};
