/**
 * Политика наблюдений за статусом сделки на площадке.
 *
 * @remarks
 * Модуль отвечает на один вопрос: что делать с пришедшим `TradeStatus`, если
 * по этой сделке уже что-то известно.
 *
 * Вопрос доменный, а не прикладной. Он целиком выводится из контракта
 * `TradeStatus` — какие статусы финальны и в каком направлении площадка по ним
 * ходит, — и не зависит ни от того, кто наблюдает, ни от того, где хранится
 * результат. Раньше правило жило в `@polymarket/account-state` рядом с
 * состоянием аккаунта; там оно было недоступно ни одному другому потребителю
 * и повторялось бы в каждом следующем.
 *
 * Ключевое различение — между порядком СОБЫТИЙ на площадке и порядком их
 * ДОСТАВКИ. Площадка назад не ходит; сообщения приходят как придётся.
 */

import type { TradeStatus } from './ExecutionMetadata.js';

/**
 * Статусы, из которых площадка уже не выходит.
 *
 * @remarks
 * По контракту `TradeStatus`: `CONFIRMED` — «finality достигнута, транзакция
 * успешна», `FAILED` — «транзакция окончательно упала, повторов не будет».
 *
 * `MATCHED`, `MINED` и `RETRYING` терминальными НЕ являются — из них площадка
 * ходит дальше. В частности, `MINED` означает лишь попадание расчётной
 * транзакции в блок, а не достижение финальности.
 */
export const TERMINAL_TRADE_STATUSES: ReadonlySet<TradeStatus> = new Set<TradeStatus>([
  'CONFIRMED',
  'FAILED',
]);

/**
 * Достигла ли сделка статуса, из которого площадка уже не выйдет.
 *
 * @param status - Статус сделки на площадке
 * @returns `true`, если статус терминальный
 *
 * @example
 * ```typescript
 * isTerminalTradeStatus('CONFIRMED'); // true
 * isTerminalTradeStatus('MINED');     // false — блок ≠ финальность
 * ```
 */
export function isTerminalTradeStatus(status: TradeStatus): boolean {
  return TERMINAL_TRADE_STATUSES.has(status);
}

/**
 * Как потребитель обязан поступить с пришедшим наблюдением.
 *
 * @remarks
 * Три из четырёх исходов состояние НЕ меняют, и только один из них —
 * `CONFLICT` — является ошибкой. Различать `DUPLICATE` и `STALE` полезно для
 * диагностики: первое означает повторную доставку, второе — переупорядочивание.
 */
export type TradeStatusObservation =
  /** Наблюдение новее известного — записать */
  | 'ACCEPT'
  /** Тот же статус пришёл ещё раз — ничего не делать */
  | 'DUPLICATE'
  /** Нетерминальный статус после терминального: наблюдение сделано раньше, доехало позже */
  | 'STALE'
  /** Два РАЗНЫХ терминальных исхода у одной сделки — задержкой не объясняется */
  | 'CONFLICT';

/**
 * Классифицирует наблюдение за статусом сделки.
 *
 * @param current - Уже известный статус этой сделки
 * @param incoming - Пришедший статус
 * @returns Что потребитель обязан сделать с наблюдением
 *
 * @remarks
 * Правило целиком:
 *
 * ```text
 * current == incoming                DUPLICATE
 * терминальный → нетерминальный      STALE
 * терминальный → другой терминальный CONFLICT
 * нетерминальный → любой             ACCEPT
 * ```
 *
 * `current` НЕ принимает `undefined`: отсутствие наблюдений — не вопрос
 * политики, первое наблюдение принимается всегда. Если бы аргумент был
 * необязательным, потребителю пришлось бы приводить тип в ветке `CONFLICT` —
 * компилятор не проносит сужение через вызов, — а приведение типа в денежном
 * пути проверить нечем.
 *
 * `MINED` после `CONFIRMED` — это не «сделка перестала быть подтверждённой», а
 * наблюдение, сделанное РАНЬШЕ и доехавшее позже. Возвращать по нему ошибку
 * нельзя: у потребителя такое сообщение обычно приходит по подписке, и
 * штатное переупорядочивание сети превращалось бы в аварийный отказ.
 *
 * Единственное, что задержкой не объясняется, — два разных терминальных
 * исхода у одной сделки: площадка не могла сообщить и `CONFIRMED`, и `FAILED`.
 * Здесь мы действительно не понимаем происходящего и обязаны остановиться.
 *
 * Функция ничего не решает за потребителя: она не бросает, не логирует и не
 * знает, чем `CONFLICT` обернётся выше — ошибкой, метрикой или сверкой.
 *
 * @example
 * ```typescript
 * if (current === undefined) return save(incoming); // первое наблюдение
 *
 * switch (classifyTradeStatusObservation(current, incoming)) {
 *   case 'ACCEPT':    return save(incoming);
 *   case 'DUPLICATE':
 *   case 'STALE':     return Ok(undefined);
 *   case 'CONFLICT':  return Err(new TerminalStatusConflictError(...));
 * }
 * ```
 */
export function classifyTradeStatusObservation(
  current: TradeStatus,
  incoming: TradeStatus,
): TradeStatusObservation {
  if (current === incoming) return 'DUPLICATE';
  if (!isTerminalTradeStatus(current)) return 'ACCEPT';
  return isTerminalTradeStatus(incoming) ? 'CONFLICT' : 'STALE';
}
