/**
 * Формулы верхушки стакана в машинной точности.
 *
 * @remarks
 * Те же величины, что считает {@link bookPricing}, но на `number` вместо
 * `Decimal` и по голым числам вместо сущности `Orderbook`.
 *
 * ### Зачем вторая точность
 *
 * `bookPricing` работает с `Orderbook<TPrice>` и `Decimal` — это правильно
 * там, где число становится ценой домена и попадает в деньги. Но два
 * потребителя не могут его использовать по причинам, не связанным с
 * аккуратностью:
 *
 * - горячий путь рыночных данных держит top-N уровней сырыми числами ради
 *   памяти, и собирать `Orderbook` на каждое обновление книги слишком дорого;
 * - офлайн-анализ читает записанные архивы, где уровни тоже просто числа.
 *
 * Раньше оба переписывали формулы у себя, и вместе с `bookPricing` их
 * существовало ТРИ копии. Копии совпадали, но микроцена — формула, которую
 * легко написать наоборот (см. ниже), и хранить её в трёх местах опасно.
 *
 * ### Соглашение
 *
 * Эти функции — не «упрощённая версия», а тот же контракт при другой
 * точности. Их согласие с `bookPricing` закреплено тестом; расходиться им
 * нельзя. Если формула меняется — меняется в обоих местах сразу.
 *
 * Величины здесь безразмерны и не являются ценами домена: у них нет ни
 * валюты, ни диапазона исхода. Превращать их в `OutcomePrice`/`AssetPrice`
 * должен вызывающий — на границе своего слоя.
 */

/**
 * Середина между лучшими котировками.
 *
 * @param bid - Лучшая цена покупки
 * @param ask - Лучшая цена продажи
 * @returns Среднее арифметическое
 *
 * @example
 * ```typescript
 * midpoint(0.48, 0.52); // 0.5
 * ```
 */
export function midpoint(bid: number, ask: number): number {
  return (bid + ask) / 2;
}

/**
 * Микроцена — середина, смещённая к стороне с меньшей очередью.
 *
 * @param bid - Лучшая цена покупки
 * @param ask - Лучшая цена продажи
 * @param bidQty - Объём на лучшей покупке
 * @param askQty - Объём на лучшей продаже
 * @returns Микроцена, либо `null`, если суммарный объём нулевой
 *
 * @remarks
 * ```text
 * microprice = (ask × bidQty + bid × askQty) / (bidQty + askQty)
 * ```
 *
 * Взвешивание ПЕРЕКРЁСТНОЕ: `ask` умножается на объём покупки, а `bid` — на
 * объём продажи. Это не опечатка и не произвол. Большая очередь на покупке
 * означает, что следующая сделка вероятнее пройдёт по `ask`, — поэтому вес
 * этой очереди достаётся противоположной цене.
 *
 * Написанная «прямо» (`bid × bidQty + ask × askQty`) формула даёт смещение в
 * обратную сторону и выглядит правдоподобно — именно поэтому она живёт здесь
 * одна, а не переписывается у каждого потребителя.
 *
 * Отрицательные объёмы вызывающий обязан отсечь заранее: здесь они не
 * проверяются, потому что функция стоит на горячем пути.
 *
 * @example
 * ```typescript
 * // очередь на покупке толще → цена тянется к ask
 * microprice(0.48, 0.52, 900, 100); // 0.516
 * microprice(0.48, 0.52, 100, 900); // 0.484
 * ```
 */
export function microprice(
  bid: number,
  ask: number,
  bidQty: number,
  askQty: number,
): number | null {
  const totalQty = bidQty + askQty;
  if (totalQty <= 0) return null;
  return (ask * bidQty + bid * askQty) / totalQty;
}

/**
 * Перекос объёмов верхушки.
 *
 * @param bidQty - Объём на лучшей покупке
 * @param askQty - Объём на лучшей продаже
 * @returns Значение в диапазоне [-1, 1], либо `null` при нулевом объёме
 *
 * @remarks
 * ```text
 * imbalance = (bidQty − askQty) / (bidQty + askQty)
 * ```
 *
 * Положительное значение — перевес покупателей.
 *
 * @example
 * ```typescript
 * imbalance(900, 100); // 0.8
 * ```
 */
export function imbalance(bidQty: number, askQty: number): number | null {
  const totalQty = bidQty + askQty;
  if (totalQty <= 0) return null;
  return (bidQty - askQty) / totalQty;
}

/**
 * Спред в базисных пунктах от середины.
 *
 * @param bid - Лучшая цена покупки
 * @param ask - Лучшая цена продажи
 * @returns Спред в bps, либо `null` при нулевой середине
 *
 * @example
 * ```typescript
 * spreadBps(0.48, 0.52); // 800
 * ```
 */
export function spreadBps(bid: number, ask: number): number | null {
  const mid = midpoint(bid, ask);
  if (mid === 0) return null;
  return ((ask - bid) / mid) * 10_000;
}
