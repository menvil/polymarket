/**
 * MarketSpec — предметная спецификация рынка для конкретного {@link MarketFamily}
 *
 * @remarks
 * Семейство говорит, *как устроен* рынок; спецификация — *о чём именно* он.
 * Для `CRYPTO_UP_DOWN` это базовый криптоактив и номинальная длительность серии.
 *
 * ### Почему спецификация вынесена из Market «плоскими» полями
 * Поля вида `asset`/`duration` осмысленны только внутри своего семейства.
 * Плоские опциональные поля на Market означали бы, что любая комбинация
 * допустима на уровне типа, и каждый потребитель обязан проверять их сам.
 * Отдельный объект под ключом семейства (`market.crypto`) делает связку
 * «семейство → спецификация» явной и проверяемой в `Market.create()`.
 *
 * ### Почему это не иерархия «на все случаи»
 * Спецификация есть не у каждого семейства: `BINARY_OUTCOME` — бинарный рынок
 * общего вида — не несёт никакой, и `Market.create()` ему её запрещает.
 * Добавление семейства СО спецификацией — это новый интерфейс здесь, новый
 * литерал в {@link MarketFamily} и новое необязательное поле на Market рядом
 * с `crypto`. Заранее строить общую абстракцию смысла нет: её форма
 * определяется тем, какие поля реально понадобятся конкретному семейству.
 *
 * @example
 * ```typescript
 * import { unsafeCryptoAssetId } from '@polymarket/ids';
 *
 * const spec: CryptoUpDownSpec = {
 *   asset: unsafeCryptoAssetId('btc'),
 *   duration: asMarketDuration(5 * 60_000)!,
 * };
 * ```
 */

import type { CryptoAssetId } from '@polymarket/ids';
import type { MarketDuration } from './MarketDuration.js';

/**
 * CryptoUpDownSpec — спецификация семейства `CRYPTO_UP_DOWN`
 *
 * @remarks
 * Описывает бинарный рынок «цена актива вырастет/упадёт за окно».
 * Оба поля структурные: они известны при обнаружении рынка и не меняются.
 */
export interface CryptoUpDownSpec {
  /** Базовый криптоактив рынка (`'btc'`, `'eth'`, ...) */
  readonly asset: CryptoAssetId;
  /**
   * Номинальная длительность серии рынка (5 минут, 1 час, ...)
   *
   * @remarks
   * Это классификация серии, а не измеренная длина окна — фактический
   * интервал даёт `Market.duration()`. Подробности расхождения см. в
   * TSDoc {@link MarketDuration}.
   */
  readonly duration: MarketDuration;
}
