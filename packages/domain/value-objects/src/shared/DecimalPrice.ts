/**
 * DecimalPrice — минимальный контракт «это цена».
 *
 * @remarks
 * ## Зачем
 *
 * В системе живут ДВА ценовых домена, и они несовместимы по инвариантам:
 *
 * ```text
 * Price           [0.0001, 0.9999]   доля исхода рынка предсказаний
 * ReferencePrice  (0, ∞)             цена внешнего актива (BTC/USD)
 * ```
 *
 * Структуры, которые лишь ХРАНЯТ цены и выбирают из них (стакан, уровень,
 * спред), не должны зависеть ни от одного из этих доменов: стакан Binance
 * на 78 468 и стакан outcome-токена на 0.52 — одна и та же структура
 * данных с разным доменом значений. Этот интерфейс и есть то общее, что им
 * от цены нужно.
 *
 * ## Почему один метод
 *
 * Контракт намеренно МИНИМАЛЕН. Всё, что структуре реально требуется, —
 * получить точное значение для сравнения и сортировки; сравнение делается
 * через `value().comparedTo(...)`, и отдельные `isLessThan`/`equals` в
 * контракте не нужны. Чем шире интерфейс, тем труднее ему соответствовать
 * будущим типам цены — а смысл здесь ровно обратный.
 *
 * `Price` и `ReferencePrice` удовлетворяют ему СТРУКТУРНО, без единой
 * правки в них самих и без явного `implements`.
 *
 * ## Чего здесь НЕТ
 *
 * Ни создания цены из `Decimal`, ни арифметики. Создать новое значение
 * (mid price, микроцена, ширина спреда) можно только зная домен, поэтому
 * фабрика передаётся вызывающим, а не прячется в структуре — см.
 * `bookPricing` в `@polymarket/orderbook`.
 *
 * @example
 * ```typescript
 * // Структура, работающая с любым ценовым доменом
 * function bestOf<T extends DecimalPrice>(prices: readonly T[]): T | undefined {
 *   return prices.reduce<T | undefined>(
 *     (best, p) => (best === undefined || p.value().greaterThan(best.value()) ? p : best),
 *     undefined,
 *   );
 * }
 *
 * bestOf([outcomePrice]);   // Price
 * bestOf([assetPrice]);     // ReferencePrice
 * ```
 */
import type Decimal from 'decimal.js';

export interface DecimalPrice {
  /**
   * Точное значение цены.
   *
   * @returns `Decimal` без потери точности
   */
  value(): Decimal;
}
