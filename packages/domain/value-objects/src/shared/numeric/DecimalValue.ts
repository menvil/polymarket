import type Decimal from 'decimal.js';

/**
 * Минимальный контракт «это числовая величина».
 *
 * @remarks
 * Ровно то, что нужно общим структурам и операциям от ЛЮБОГО числового
 * value object: способ получить точное значение. Ни диапазона, ни единиц
 * измерения, ни домена контракт не знает — иначе он перестал бы быть
 * общим.
 *
 * Инварианты (диапазон, знак, шаг) остаются за доменом: `Quantity`
 * неотрицательно, `SignedQuantity` любого знака, `OutcomePrice` лежит в
 * `[0.0001, 0.9999]`, `AssetPrice` — в `(0, ∞)`. Общий предок-класс
 * размыл бы их все.
 *
 * @example
 * ```typescript
 * // Обе величины удовлетворяют контракту, оставаясь разными типами
 * const q: DecimalValue = quantity;
 * const p: DecimalValue = outcomePrice;
 * ```
 */
export interface DecimalValue {
  /** Точное значение; `Decimal`, а не `number` — иначе теряется точность */
  value(): Decimal;
}
