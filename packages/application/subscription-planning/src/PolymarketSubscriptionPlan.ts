/**
 * Результат работы планировщика подписок: что можно приобрести и почему
 * остальное — нельзя.
 *
 * @remarks
 * ### Почему результат — не голый массив
 *
 * Пустой массив кандидатов не отличает «policy никому не подошла» от
 * «universe состоит из уже начавшихся рынков» и от «все рынки чужой
 * площадки». Это три разные операционные ситуации с тремя разными
 * действиями, и различить их по одному лишь `length === 0` нельзя. Поэтому
 * рядом с кандидатами едет разбор ПРИЧИН — ровно в том же виде, в каком
 * discovery отдаёт разбор непригодных рынков.
 *
 * ### Почему кандидат — сама запись universe, а не DTO
 *
 * Обёртка вида `PlannedMarket { entry, score, reason }` не добавила бы ни
 * одного факта: identity, расписание и наблюдения уже лежат в canonical
 * записи, а «score» и «reason» — свойства ПОРЯДКА и ОТБОРА, а не рынка.
 * Материализованные в данных, они пережили бы своё вычисление и поехали бы
 * дальше по контуру как характеристика рынка — см. TSDoc `MarketScorer` о
 * ровно этой ошибке. Поэтому `candidates` — те же самые объекты
 * `MarketDiscoveryEntry`, что пришли на вход, только в другом порядке и без
 * отклонённых.
 *
 * ### Инвариант диагностики
 *
 * ```text
 * scanned = wrongVenue
 *         + inactive
 *         + alreadyStarted
 *         + insufficientLeadTime
 *         + policyMismatch
 *         + eligible
 * ```
 *
 * Каждая запись попадает РОВНО в одну категорию — ту, по которой она
 * отсеялась ПЕРВОЙ (порядок ворот см. в TSDoc
 * `PolymarketSubscriptionPlanner`). Без этого правила один и тот же рынок
 * считался бы дважды, сумма перестала бы сходиться, и по диагностике нельзя
 * было бы ответить на единственный вопрос, ради которого она заведена:
 * «почему этой записи нет в плане».
 */
import type { MarketDiscoveryEntry } from '@polymarket/ports';
import type { Timestamp } from '@polymarket/timestamp';

/**
 * Разбор одного прогона планировщика по ПРИЧИНАМ отказа.
 *
 * @remarks
 * Счётчики, а не списки идентификаторов: план строится на каждом тике
 * runtime, и хранить в нём копию universe с разбивкой по причинам означало
 * бы платить памятью за диагностику, которая нужна для наблюдаемости, а не
 * для принятия решений. Кто именно отсеялся, всегда воспроизводимо: планер
 * детерминирован, вход тот же.
 *
 * @example
 * ```typescript
 * const { diagnostics } = planner.plan(entries, policy, now);
 * if (diagnostics.eligible === 0 && diagnostics.alreadyStarted > 0) {
 *   // universe есть, но мы опоздали ко всем рынкам — вопрос к cadence
 *   // discovery, а не к policy
 * }
 * ```
 */
export interface PolymarketSubscriptionPlanDiagnostics {
  /** Сколько записей просмотрено (размер поданного массива). */
  readonly scanned: number;
  /** Записи чужой площадки. */
  readonly wrongVenue: number;
  /** Рынки, состояние которых площадка объявила терминальным. */
  readonly inactive: number;
  /** Рынки, торги по которым уже идут (включая старт РОВНО сейчас). */
  readonly alreadyStarted: number;
  /** Рынки, до старта которых осталось меньше минимального запаса. */
  readonly insufficientLeadTime: number;
  /** Рынки, которым policy не подходит В МОМЕНТ ИХ СТАРТА. */
  readonly policyMismatch: number;
  /** Рынки, попавшие в план. */
  readonly eligible: number;
}

/**
 * План подписок: упорядоченные пригодные рынки + разбор отказов.
 *
 * @remarks
 * Иммутабелен целиком: заморожены и сам план, и массив кандидатов, и
 * диагностика. `readonly` в типах — обещание компилятору, а план уезжает к
 * потребителям (контроллер подписок, метрики, логи), у которых нет причин
 * его править и есть все возможности сделать это случайно.
 *
 * План НЕ содержит ни владельцев, ни claim-ов, ни счётчиков ссылок, ни
 * желаемого количества рынков: «сколько из пригодных держать» — вопрос
 * следующего слоя, у которого есть физический ресурс. Здесь только
 * «пригодны и в каком порядке».
 *
 * @example
 * ```typescript
 * const plan = planner.plan(universe.getAll(), policy, now);
 *
 * const next = plan.candidates[0];          // ближайший доступный рынок
 * const firstThree = plan.candidates.slice(0, 3); // сколько нужно — решает потребитель
 * ```
 */
export interface PolymarketSubscriptionPlan {
  /**
   * Момент, НА который построен план.
   *
   * @remarks
   * Ровно тот `now`, что передан в `plan()`: планировщик часов не читает.
   * Поле нужно потребителю, чтобы план нельзя было интерпретировать в
   * другой момент времени, чем тот, в котором он посчитан.
   */
  readonly plannedAt: Timestamp;
  /**
   * Пригодные рынки в порядке `MarketScorer`.
   *
   * @remarks
   * Те же объекты записей, что пришли на вход. Уже начавшихся рынков здесь
   * нет по построению, поэтому `candidates[0]` — БЛИЖАЙШИЙ ПРЕДСТОЯЩИЙ
   * рынок, а не самый старый из всех.
   */
  readonly candidates: readonly MarketDiscoveryEntry[];
  /** Разбор прогона по причинам отказа. */
  readonly diagnostics: PolymarketSubscriptionPlanDiagnostics;
}
