/**
 * Ранжирование записей universe: «какой рынок следующий».
 *
 * @remarks
 * ### Порядок — свойство ПОСЛЕДОВАТЕЛЬНОСТИ, а не рынка
 *
 * Скорер не проставляет записям числовой `score` и вообще ничего в них не
 * дописывает. Материализованный score — это кэш решения одной конкретной
 * сортировки, положенный в данные: он переживает свою сортировку, уезжает
 * дальше по контуру вместе с рынком и читается следующим потребителем как
 * характеристика РЫНКА, хотя характеристикой рынка никогда не был. Ровно
 * так и появляется «рынок с плохим скором» — утверждение, которое нельзя
 * ни проверить, ни опровергнуть, потому что неизвестно, относительно какого
 * набора и какого момента этот скор считался.
 *
 * Поэтому здесь чистая ранжирующая функция: на входе записи, на выходе те же
 * самые записи в другом порядке. Ответ живёт в порядке массива и нигде больше.
 *
 * ### Почему первичный ключ — `startsAt`, а не `expiresAt`
 *
 * Прежний контур ранжировал уже АКТИВНЫХ кандидатов, и «ближайшее истечение»
 * там было разумным: все рынки уже торгуются, вопрос лишь в том, который
 * разрешится раньше. Новый universe содержит и БУДУЩИЕ рынки, а вопрос к нему
 * звучит иначе — «какой рынок следующий?». Ответ на него даёт только начало
 * торгов: рынок, стартующий через минуту, идёт раньше рынка, стартующего
 * через час, независимо от того, который из них истечёт первым.
 *
 * `expiresAt` остаётся вторым ключом расписания — он разводит рынки одной и
 * той же серии, стартующие одновременно, но закрывающиеся в разное время.
 *
 * ### Почему нет часов
 *
 * Скорер не принимает `IClock` и не читает время. Порядок определяется
 * СРАВНЕНИЕМ полей записей между собой, а не расстоянием до «сейчас»: любая
 * монотонная функция от `now` дала бы ровно тот же порядок, зато сделала бы
 * результат невоспроизводимым и добавила бы скореру зависимость, которой у
 * него нет по существу задачи.
 *
 * ### Скорер ничего не отбрасывает
 *
 * Ни policy, ни актив, ни длительность, ни ключевые слова, ни окно
 * применимости: `MarketFilter` отвечает «подходит / не подходит», а
 * `MarketScorer` — «в каком порядке». Разделение строгое. Скорер, умеющий
 * отбрасывать, превращает отбор в функцию порядка входа: результат начинает
 * зависеть от того, в каком месте списка стоял рынок, а не от его свойств, и
 * два одинаковых прогона над одним universe законно расходятся.
 *
 * ```text
 * MarketDiscoveryEntry[]  →  MarketFilter  →  MarketScorer  →  ranked[]
 *                            подходит?         порядок
 * ```
 */
import type { MarketDiscoveryEntry } from '@polymarket/ports';
import type { Timestamp } from '@polymarket/timestamp';
import type { Money } from '@polymarket/value-objects';

/**
 * Ранжирующая функция Policy-контура: детерминированный порядок записей
 * universe.
 *
 * @remarks
 * Stateless и без зависимостей — конструктор пуст намеренно. Экземпляр можно
 * держать один на процесс; никакого состояния между вызовами `rank()` нет.
 *
 * @example
 * ```typescript
 * const scorer = new MarketScorer();
 * const ranked = scorer.rank(filter.filter(universe.getAll(), policy, now));
 * const next = ranked[0]; // рынок, который начнётся раньше остальных
 * ```
 */
export class MarketScorer {
  /**
   * Ранжирует записи universe по приоритету «какой рынок следующий».
   *
   * @param entries - Записи universe (уже прошедшие `MarketFilter`, если он нужен)
   * @returns НОВЫЙ массив с теми же записями в порядке приоритета
   * @throws Ничего не бросает: ранжирование не отказывает ни на каких данных
   *
   * @remarks
   * ### Составной ключ (строго в этом порядке)
   *
   * ```text
   * 1. market.startsAt    ASC   ← «какой рынок следующий»
   * 2. market.expiresAt   ASC   ← второй ключ расписания
   * 3. metrics.liquidity  DESC  ← при одинаковом расписании берём ликвиднее
   * 4. market.venueId     ASC   ← identity: полный детерминизм
   * 5. market.id          ASC
   * ```
   *
   * Ликвидность стоит НИЖЕ обоих ключей расписания и потому никогда не
   * перебивает более ранний старт. Это не вкусовщина: ликвидность —
   * наблюдение, которое меняется каждую минуту, а расписание рынка — факт.
   * Пусти ликвидность выше, и порядок начнёт скакать между обходами discovery
   * при неизменном расписании, а «следующий рынок» перестанет быть следующим.
   *
   * ### Почему хвост из identity обязателен
   *
   * Ключи 4–5 не декоративные. Без них рынки с одинаковым расписанием и
   * одинаковой ликвидностью остаются взаимно «равными», и их взаимный порядок
   * определяется порядком ВХОДА. Тогда один и тот же universe, пришедший из
   * двух обходов в разном порядке, даёт две разные вершины ранжирования — при
   * полностью идентичных данных. Пара `venueId + marketId` — идентичность
   * рынка (тот же ключ, что у дедупликации universe), поэтому после неё
   * равных элементов не остаётся вовсе: сравнение — строгий полный порядок.
   *
   * ### Что НЕ участвует
   *
   * Спред: он необязателен (`undefined` = «площадка не отдала»), и любое его
   * место в порядке потребовало бы решить, куда девать записи без него —
   * то есть выдумать значение там, где данных нет. Порог по спреду — вопрос
   * пригодности, а это `MarketFilter`.
   *
   * Вход не мутируется: сортируется КОПИЯ массива, а сами записи возвращаются
   * теми же объектами — скорер их не пересобирает и ничего в них не дописывает.
   *
   * @example
   * ```typescript
   * const scorer = new MarketScorer();
   *
   * // A стартует позже, но ликвиднее; B стартует раньше
   * const ranked = scorer.rank([entryA, entryB]);
   *
   * ranked[0] === entryB; // true — ранний старт важнее ликвидности
   * ranked.length === 2;  // ничего не отброшено: скорер не фильтрует
   * ```
   */
  public rank(entries: readonly MarketDiscoveryEntry[]): MarketDiscoveryEntry[] {
    // Копия: сортировка на месте изменила бы массив вызывающего.
    return [...entries].sort((a, b) => MarketScorer._compareEntries(a, b));
  }

  /**
   * Сравнивает две записи по составному ключу ранжирования.
   *
   * @param a - Первая запись
   * @param b - Вторая запись
   * @returns Отрицательное — `a` раньше, положительное — `b` раньше, `0` — записи неразличимы
   *
   * @remarks
   * Ключи применяются последовательно: следующий работает только когда
   * предыдущий дал `0`. Ноль возвращается лишь для записей с одинаковой
   * identity, то есть для одного и того же рынка.
   */
  private static _compareEntries(a: MarketDiscoveryEntry, b: MarketDiscoveryEntry): number {
    const byStart = MarketScorer._compareTimestampsAsc(a.market.startsAt, b.market.startsAt);
    if (byStart !== 0) return byStart;

    const byExpiry = MarketScorer._compareTimestampsAsc(a.market.expiresAt, b.market.expiresAt);
    if (byExpiry !== 0) return byExpiry;

    const byLiquidity = MarketScorer._compareLiquidityDesc(
      a.metrics.liquidity,
      b.metrics.liquidity
    );
    if (byLiquidity !== 0) return byLiquidity;

    const byVenue = MarketScorer._compareStringsAsc(a.market.venueId, b.market.venueId);
    if (byVenue !== 0) return byVenue;

    return MarketScorer._compareStringsAsc(a.market.id, b.market.id);
  }

  /**
   * Сравнивает две отметки времени по возрастанию.
   *
   * @param a - Первая отметка
   * @param b - Вторая отметка
   * @returns `-1` если `a` раньше, `1` если позже, `0` при совпадении
   *
   * @remarks
   * Через canonical-операции `Timestamp`, а не через разность `toNumber()`.
   * Разность миллисекунд — это выход за границу value object: она молча
   * возвращает нас к сырым числам, теряет смысл на epoch-когерентных
   * hi-res отметках и способна переполнить безопасный диапазон на
   * произвольных значениях. Отношение «раньше/позже» value object выражает
   * сам, и спрашивать надо именно его.
   */
  private static _compareTimestampsAsc(a: Timestamp, b: Timestamp): number {
    if (a.isBefore(b)) return -1;
    if (a.isAfter(b)) return 1;
    return 0;
  }

  /**
   * Сравнивает ликвидность двух записей: больше — раньше.
   *
   * @param a - Ликвидность первой записи
   * @param b - Ликвидность второй записи
   * @returns Отрицательное — `a` раньше (ликвиднее), положительное — `b` раньше, `0` при равенстве
   *
   * @remarks
   * ### Разные валюты
   *
   * Теоретически записи могут прийти в разных валютах, и сравнивать их суммы
   * напрямую нельзя: «100 USDC против 100 чего-то ещё» — сравнение чисел, а не
   * денег, и молча вводит курс 1:1, которого никто не объявлял. Бросить
   * исключение тоже нельзя: отказ на ранжировании уронил бы весь отбор из-за
   * одной инородной записи, хотя расписание — главный ключ — прекрасно
   * определено для всех.
   *
   * Поэтому при РАЗНЫХ валютах сравнение идёт по коду валюты ASC, и суммы
   * сравниваются только ВНУТРИ одной валюты. Записи группируются по валюте в
   * стабильном порядке, курс не выдумывается, отказа нет.
   *
   * Соблазнительная альтернатива — «валюты разные, считаем ничьёй и падаем на
   * identity» — неверна, и это не вопрос вкуса. Такое сравнение
   * НЕТРАНЗИТИВНО: `A(USDC 1)` уступает `B(USDC 100)` по сумме, но обе
   * сравниваются с `C(другая валюта)` по identity, и легко подобрать id, при
   * которых получается цикл `B < A < C < B`. Массив с циклическим компаратором
   * сортируется как получится — ровно тот недетерминизм, против которого
   * заведён identity-хвост. Лексикографический порядок «(валюта, −сумма)»
   * транзитивен по построению.
   *
   * На практике ветка почти недостижима: discovery отдаёт ликвидность в USDC,
   * а отсутствующее значение — как `Money.of(0, 'USDC')`. Она существует,
   * чтобы отсутствие FX-политики было ЯВНЫМ, а не удачным стечением данных.
   */
  private static _compareLiquidityDesc(a: Money, b: Money): number {
    const currencyA = a.currency();
    const currencyB = b.currency();
    if (currencyA !== currencyB) {
      return MarketScorer._compareStringsAsc(currencyA, currencyB);
    }

    // DESC: большая ликвидность идёт раньше, поэтому операнды переставлены.
    return b.value().comparedTo(a.value());
  }

  /**
   * Сравнивает две строки по возрастанию кодовых единиц.
   *
   * @param a - Первая строка
   * @param b - Вторая строка
   * @returns `-1` если `a` раньше, `1` если позже, `0` при равенстве
   *
   * @remarks
   * Именно `<`/`>`, а не `localeCompare()`: последний зависит от локали среды,
   * и один и тот же universe ранжировался бы по-разному на машине разработчика
   * и на проде. Ключ здесь технический — от него нужен детерминизм, а не
   * читаемость алфавита.
   */
  private static _compareStringsAsc(a: string, b: string): number {
    if (a < b) return -1;
    if (a > b) return 1;
    return 0;
  }
}
