/**
 * Правило совпадения ключевого слова с текстом рынка — ОДНО на весь пакет.
 *
 * @remarks
 * ### Почему это отдельный модуль
 *
 * Правило нужно двум разным местам, и они задают ему разные вопросы:
 *
 * - `MarketFilter` — «совпадает ли слово с вопросом рынка»;
 * - `createPolymarketPolicy` — «эквивалентны ли два слова», чтобы поймать
 *   противоречие вида «слово одновременно в `required` и `excluded`».
 *
 * Пока у этих вопросов были ДВЕ независимые реализации, они разошлись —
 * и разошлись незаметно. Фабрика сравнивала слова через `toLowerCase()`, а
 * матчер сопоставляет их регексом под флагами `iu`, то есть по юникодному
 * case folding. Это не одно и то же:
 *
 * ```text
 * 'S'.toLowerCase() === 'ſ'.toLowerCase()   → false   (фабрика: конфликта нет)
 * /S/iu.test('ſ')                           → true    (матчер: слова совпадают)
 * ```
 *
 * Значит policy `required: ['S'], excluded: ['ſ']` проходила валидацию и
 * при этом была невыполнима — ровно тот класс дефекта, ради которого
 * проверка противоречий и добавлялась.
 *
 * Поэтому эквивалентность здесь выводится ИЗ САМОГО матчера, а не
 * реализуется параллельно ему: разойтись с собой он не может.
 */

/**
 * Спецсимволы регулярных выражений, требующие экранирования.
 *
 * @internal
 */
const REGEX_SPECIAL_CHARS = /[.*+?^${}()|[\]\\]/g;

/**
 * Компилирует ключевое слово в регекс с ЮНИКОДНЫМИ границами слова.
 *
 * @param keyword - Ключевое слово как его задал автор policy
 * @returns Регекс, совпадающий со словом, но не с его вхождением внутрь
 *   более длинного буквенно-цифрового токена
 * @throws Ничего не бросает: спецсимволы экранируются до компиляции
 *
 * @remarks
 * Границы заданы явными lookbehind/lookahead, а НЕ `\b`: `\b` работает по
 * классу `[A-Za-z0-9_]`, поэтому в текстах площадки с апострофами, дефисами
 * и подчёркиваниями его поведение непредсказуемо. Lookaround говорит правило
 * прямо: ключевое слово не должно быть частью более длинного токена.
 *
 * Класс границы — `[\p{L}\p{N}\p{M}]` под флагами `iu`, а не ASCII
 * `[a-zA-Z0-9]`:
 *
 * - `\p{L}`/`\p{N}` — с ASCII-классом любая нелатинская буква считалась бы
 *   пунктуацией, и `Биткоинup` дал бы совпадение по слову `up`;
 * - `\p{M}` — комбинирующие знаки: в разложенной форме (NFD) последним
 *   символом слова оказывается знак, а не буква, и без `\p{M}` он читался бы
 *   как разделитель.
 *
 * Флаг `i` даёт регистронезависимость (в том числе для нелатиницы), поэтому
 * `toLowerCase()` над текстом не нужен. Флаг `g` НЕ ставится сознательно:
 * с ним `RegExp.test` тащит `lastIndex` между вызовами, и один и тот же
 * регекс, переиспользованный по списку рынков, давал бы разные ответы.
 *
 * @example
 * ```typescript
 * compileKeywordRegex('war').test('the war in Ukraine'); // → true
 * compileKeywordRegex('war').test('reward');             // → false
 * compileKeywordRegex('c++').test('learn c++ today');    // → true (экранирование)
 * ```
 */
export function compileKeywordRegex(keyword: string): RegExp {
  const escaped = keyword.replace(REGEX_SPECIAL_CHARS, '\\$&');
  return new RegExp(`(?<![\\p{L}\\p{N}\\p{M}])${escaped}(?![\\p{L}\\p{N}\\p{M}])`, 'iu');
}

/**
 * Считает ли МАТЧЕР два ключевых слова одним и тем же словом.
 *
 * @param a - Первое ключевое слово
 * @param b - Второе ключевое слово
 * @returns `true`, если для матчера это неразличимые слова
 * @throws Ничего не бросает
 *
 * @remarks
 * Эквивалентность проверяется ВЗАИМНЫМ совпадением: регекс слова `a` должен
 * совпасть с текстом `b` И наоборот. Односторонней проверки недостаточно, и
 * это не перестраховка:
 *
 * ```text
 * regex('war').test('war war')   → true    ← вхождение, а не эквивалентность
 * regex('war war').test('war')   → false
 * ```
 *
 * При односторонней проверке `required: ['war'], excluded: ['war war']`
 * объявили бы противоречием, хотя текст `"war"` этой policy удовлетворяет:
 * требуемое слово есть, запрещённой фразы нет. Взаимное совпадение отсекает
 * такие вхождения и оставляет ровно то, что нужно, — юникодные варианты
 * записи одного слова (`BTC`/`btc`, `S`/`ſ`).
 *
 * Определение опирается на {@link compileKeywordRegex}, то есть на само
 * правило матчинга. Отдельной таблицы соответствий здесь нет намеренно:
 * любая своя реализация case folding — это второй источник истины, который
 * рано или поздно разойдётся с первым.
 *
 * @example
 * ```typescript
 * areKeywordsEquivalent('BTC', 'btc');      // → true
 * areKeywordsEquivalent('S', 'ſ');          // → true (юникодный вариант записи)
 * areKeywordsEquivalent('war', 'reward');   // → false
 * areKeywordsEquivalent('war', 'war war');  // → false (вхождение, не равенство)
 * ```
 */
export function areKeywordsEquivalent(a: string, b: string): boolean {
  return compileKeywordRegex(a).test(b) && compileKeywordRegex(b).test(a);
}
