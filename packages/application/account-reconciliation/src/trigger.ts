/**
 * Причины, по которым внешний рантайм запрашивает сверку.
 *
 * @remarks
 * Координатор причину НЕ интерпретирует: проход выполняется одинаково для
 * любой из них. Она запоминается в health для диагностики — «почему был
 * последний проход».
 *
 * Когда наступает каждая из причин, решает будущий runtime wiring, а не этот
 * пакет: внутренних таймеров, cron и каденций здесь нет.
 *
 * ```text
 * STARTUP        аккаунт принят рантаймом, состояние ещё не подтверждено
 * PERIODIC       плановая сверка (частоту выбирает рантайм)
 * RECONNECT      приватный поток переподключился — события могли потеряться
 * MANUAL         оператор попросил явно
 * INCONSISTENCY  живой контур заметил расхождение
 * ```
 */
export type AccountReconciliationTrigger =
  | 'STARTUP'
  | 'PERIODIC'
  | 'RECONNECT'
  | 'MANUAL'
  | 'INCONSISTENCY';
