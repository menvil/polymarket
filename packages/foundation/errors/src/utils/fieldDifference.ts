/**
 * Единая форма «первого найденного расхождения».
 *
 * @remarks
 * В коде несколько мест сравнивают два экземпляра одной сущности и сообщают,
 * ЧЕМ они разошлись: неизменяемый факт исполнения, идентичность заявки,
 * структура рынка. Все они отвечают на один вопрос и все кладут ответ в
 * контекст ошибки, но форму ответа каждый выбирал сам — и они успели
 * разойтись в именах пары значений.
 *
 * Тип существует, чтобы у этого ответа была одна форма, проверяемая
 * компилятором, а не соглашение, которое соблюдают по памяти.
 */

/**
 * Первое найденное расхождение по одному полю.
 *
 * @typeParam TField - Union имён полей, по которым сущности могут разойтись
 *
 * @remarks
 * Возвращается ПЕРВОЕ расхождение, а не список: для отказа достаточно одного,
 * а перечислять все — лишняя работа на горячем пути ради сообщения, которое
 * всё равно читают целиком.
 *
 * Значения приведены к строкам ДЛЯ ЛОГА. Само сравнение выполняется по value
 * objects и canonical-равенствам, а не по этим строкам: `Decimal`, `Timestamp`
 * и branded-типы в строковом виде сравнивались бы неверно.
 *
 * ### Почему `left`/`right`, а не роли
 *
 * Имена нейтральны намеренно. Функция сравнения обычно живёт в домене и не
 * знает, какой из двух экземпляров «сохранённый», а какой «пришедший»: это
 * знание принадлежит вызывающему. Он и называет роли — в тексте ошибки и в
 * ключах её контекста, где они действительно нужны:
 *
 * ```typescript
 * context: { field: d.field, admitted: d.left, incoming: d.right }
 * ```
 *
 * Обратный порядок — зашить роли в тип — заставил бы домен знать про
 * приложение, а каждое новое место сравнения выбирало бы свою пару имён.
 *
 * @example
 * ```typescript
 * export type OrderIdentityDifference = FieldDifference<OrderIdentityField>;
 *
 * const difference = findOrderIdentityDifference(stored, incoming);
 * if (difference !== undefined) {
 *   logger.warn(`order differs on ${difference.field}`);
 * }
 * ```
 */
export interface FieldDifference<TField extends string> {
  /** Поле, по которому экземпляры разошлись */
  readonly field: TField;
  /** Значение в первом аргументе сравнения */
  readonly left: string;
  /** Значение во втором аргументе сравнения */
  readonly right: string;
}
